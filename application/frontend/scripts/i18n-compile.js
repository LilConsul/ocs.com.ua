#!/usr/bin/env node

/**
 * i18n PO to TypeScript Compiler
 *
 * Compiles .po files to TypeScript ui.ts format
 *
 * Usage:
 *   bun run i18n:compile
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = resolve(__dirname, "..");

/**
 * Convert English text to a valid translation key.
 * "Hello, World!" -> "hello_world"
 */
export function textToKey(text) {
	return text
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "_")
		.replace(/^_+|_+$/g, "")
		.substring(0, 80);
}

/**
 * Unescape string from PO format
 */
export function unescapePO(str) {
	return str
		.replace(/\\n/g, "\n")
		.replace(/\\t/g, "\t")
		.replace(/\\"/g, '"')
		.replace(/\\\\/g, "\\");
}

/**
 * Parse PO file
 */
export function parsePO(content) {
	const translations = new Map(); // msgid -> msgstr
	const lines = content.split("\n");
	let currentMsgid = null;
	let currentMsgstr = null;

	for (let i = 0; i < lines.length; i++) {
		const line = lines[i].trim();

		if (line.startsWith("msgid ")) {
			if (currentMsgid && currentMsgstr !== null && currentMsgid !== "") {
				translations.set(currentMsgid, currentMsgstr);
			}
			currentMsgid = unescapePO(line.substring(7, line.length - 1));
			currentMsgstr = null;
		} else if (line.startsWith("msgstr ")) {
			currentMsgstr = unescapePO(line.substring(8, line.length - 1));
		}
	}

	// Add last entry
	if (currentMsgid && currentMsgstr !== null && currentMsgid !== "") {
		translations.set(currentMsgid, currentMsgstr);
	}

	return translations;
}

/**
 * Escape string for TypeScript
 */
export function escapeTS(str) {
	return str.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
}

/**
 * Generate TypeScript ui.ts content from POT and PO contents
 * @param {string} potContent
 * @param {Record<string, string>} poContentsByLang
 * @returns {string}
 */
export function generateUiContent(potContent, poContentsByLang) {
	const allTranslations = {};
	const potTranslations = parsePO(potContent);
	allTranslations.en = potTranslations;

	const languages = Object.keys(poContentsByLang);
	for (const lang of languages) {
		allTranslations[lang] = parsePO(poContentsByLang[lang]);
	}

	const uiData = {};
	const allLanguages = ["en", ...languages];

	for (const lang of allLanguages) {
		uiData[lang] = {};
		const translations = allTranslations[lang];

		for (const [msgid, msgstr] of translations) {
			const key = `inline.${textToKey(msgid)}`;
			// For English, use msgid; for others use msgstr (or msgid as fallback)
			uiData[lang][key] = lang === "en" ? msgid : msgstr && msgstr.trim() !== "" ? msgstr : msgid;
		}
	}

	const sortedKeys = Object.keys(uiData.en).sort();

	const buildObject = (lang) => {
		let result = "\t\t";
		const lines = [];

		for (const key of sortedKeys) {
			const value = uiData[lang][key] || "";
			const escapedValue = escapeTS(value);
			lines.push(`"${key}": "${escapedValue}"`);
		}

		result += lines.join(",\n\t\t");
		return result;
	};

	return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 *
 * This file is automatically generated by the i18n compilation script.
 *
 * To update translations:
 * 1. Edit the .po files in the 'locales/' directory
 * 2. Run: bun run i18n:compile
 *
 * Source files:
 * - locales/messages.pot (English source)
 * - locales/ua.po (Ukrainian translations)
 *
 * Generation script: scripts/i18n-compile.js
 */

export const languages = {
	en: "English",
	ua: "Українська",
};

export const defaultLang = "ua";

export const ui = {
	en: {
${buildObject("en")},
	},
	ua: {
${buildObject("ua")},
	},
} as const;
`;
}

/**
 * Compile PO files to ui.ts
 */
export function compile(rootDir = ROOT_DIR) {
	const localesDir = resolve(rootDir, "locales");
	const uiFile = resolve(rootDir, "src/i18n/ui.ts");

	console.log("[COMPILE] Compiling .po files to TypeScript...\n");

	const languages = ["ua"];

	// Load POT file for English source strings
	const potFile = resolve(localesDir, "messages.pot");
	if (!existsSync(potFile)) {
		console.error("[ERROR] Missing messages.pot file. Run 'bun run i18n:extract' first.");
		process.exit(1);
	}

	const potContent = readFileSync(potFile, "utf-8");
	const poContentsByLang = {};

	console.log(`[OK] Loaded locales/messages.pot`);

	// Load other language PO files
	for (const lang of languages) {
		const poFile = resolve(localesDir, `${lang}.po`);

		if (!existsSync(poFile)) {
			console.error(`[ERROR] Missing ${lang}.po file. Run 'bun run i18n:extract' first.`);
			process.exit(1);
		}

		poContentsByLang[lang] = readFileSync(poFile, "utf-8");
		console.log(`[OK] Loaded locales/${lang}.po`);
	}

	const uiContent = generateUiContent(potContent, poContentsByLang);

	if (existsSync(uiFile) && readFileSync(uiFile, "utf-8") === uiContent) {
		console.log(`\n[OK] Up-to-date: src/i18n/ui.ts`);
	} else {
		writeFileSync(uiFile, uiContent, "utf-8");
		console.log(`\n[OK] Compiled to src/i18n/ui.ts`);
	}
	console.log("\n[DONE] Compilation complete!");
}

// CLI entry point
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	compile();
}
